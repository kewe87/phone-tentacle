#!/usr/bin/env python3
"""Packs the web interface's files (this folder) into ../web_assets.h: gzipped byte arrays in flash.

Run it after changing index.html, app.js, app.css or icon.svg:  python3 hardware/hid_bridge/web/make_assets.py
The output is committed, so building the firmware needs no Python. gzip with mtime 0: the same input gives the
same header.
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = [("index.html", "WEB_INDEX_HTML"), ("app.js", "WEB_APP_JS"), ("app.css", "WEB_APP_CSS"),
         ("icon.svg", "WEB_ICON_SVG")]


def main():
    out = ["// Generated by web/make_assets.py from the files in web/. Do not edit.", "#pragma once",
           "#include <stdint.h>", ""]
    total = 0
    for name, sym in FILES:
        with open(os.path.join(HERE, name), "rb") as f:
            raw = f.read().replace(b"\r\n", b"\n")
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(gz)
        out.append("// %s: %d bytes, %d gzipped" % (name, len(raw), len(gz)))
        out.append("static const uint8_t %s[] = {" % sym)
        for i in range(0, len(gz), 20):
            out.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
        out.append("};")
        out.append("")
    with open(os.path.join(HERE, "..", "web_assets.h"), "w", newline="\n") as f:
        f.write("\n".join(out))
    print("web_assets.h: %d bytes gzipped" % total)


if __name__ == "__main__":
    main()
